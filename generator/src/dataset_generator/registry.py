
from dataclasses import dataclass
from typing import Literal

SupportStatus = Literal[
    "planned",
    "in_progress",
    "supported",
    "unsupported",
    "needs_review",
]

GeneratorModel = Literal[
    "canonical_invoice",
    "extended_document",
    "none",
]


@dataclass(frozen=True)
class DocumentTypeSpec:
    type_key: str
    display_name: str
    category: str
    description: str
    status: SupportStatus
    in_mvp: bool

    # Field names in the document/business schema.
    required_fields: tuple[str, ...] = ()
    optional_fields: tuple[str, ...] = ()
    conditional_fields: tuple[str, ...] = ()

    # Internal model used by the generator.
    model_kind: GeneratorModel = "extended_document"

    # Schema field -> one or more internal model paths.
    # Example: ("seller.name", "seller.address", "seller.tax_code")
    model_field_map: tuple[tuple[str, tuple[str, ...]], ...] = ()

    # Required schema fields not generated by the current model.
    unmapped_required_fields: tuple[str, ...] = ()

    def model_paths_for(self, field_name: str) -> tuple[str, ...]:
        return dict(self.model_field_map).get(field_name, ())

    def is_field_mapped(self, field_name: str) -> bool:
        return bool(self.model_paths_for(field_name))


