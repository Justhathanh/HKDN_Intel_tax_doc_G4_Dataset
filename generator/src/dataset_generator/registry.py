def get_document_type(type_key: str) -> DocumentTypeSpec:
    if type_key not in DOCUMENT_TYPE_REGISTRY:
        raise KeyError(
            f"Unsupported or unknown document type_key: '{type_key}'"
        )
    return DOCUMENT_TYPE_REGISTRY[type_key]


def get_model_field_paths(
    type_key: str,
    schema_field: str,
) -> tuple[str, ...]:
    spec = get_document_type(type_key)
    return spec.model_paths_for(schema_field)
